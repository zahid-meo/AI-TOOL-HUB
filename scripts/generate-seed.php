<?php
/**
 * Regenerates database/seed.sql from includes/tools-data.php.
 * Run after adding a tool:   php scripts/generate-seed.php
 */
declare(strict_types=1);

require_once dirname(__DIR__) . '/config/config.php';
require_once dirname(__DIR__) . '/includes/functions.php';
require_once dirname(__DIR__) . '/includes/tools-data.php';

$q = static fn (string $s): string => "'" . str_replace(["\\", "'"], ["\\\\", "''"], $s) . "'";

$sql  = "-- Auto-generated by scripts/generate-seed.php — safe to run multiple times.\n";
$sql .= "USE `ai_tool_hub`;\nSET NAMES utf8mb4;\n\n";

$sql .= "INSERT INTO `categories` (`slug`, `name`, `icon`, `sort_order`) VALUES\n";
$rows = [];
foreach (tool_categories() as $slug => $c) {
    $rows[] = '  (' . $q($slug) . ', ' . $q($c['name']) . ', ' . $q($c['icon']) . ', ' . (int) $c['sort'] . ')';
}
$sql .= implode(",\n", $rows) . "\nON DUPLICATE KEY UPDATE `name` = VALUES(`name`), `icon` = VALUES(`icon`), `sort_order` = VALUES(`sort_order`);\n\n";

$sql .= "INSERT INTO `tools` (`category_id`, `slug`, `name`, `short_description`, `icon`, `is_active`, `sort_order`, `created_at`) VALUES\n";
$rows = [];
$i = 0;
foreach (tools_all() as $slug => $t) {
    $i++;
    $rows[] = '  ((SELECT `id` FROM `categories` WHERE `slug` = ' . $q($t['cat']) . '), ' . $q($slug) . ', ' . $q($t['name']) . ', '
        . $q($t['short']) . ', ' . $q($t['icon']) . ', 1, ' . $i . ', NOW())';
}
$sql .= implode(",\n", $rows) . "\nON DUPLICATE KEY UPDATE `name` = VALUES(`name`), `short_description` = VALUES(`short_description`), "
    . "`icon` = VALUES(`icon`), `category_id` = VALUES(`category_id`), `sort_order` = VALUES(`sort_order`);\n";

file_put_contents(dirname(__DIR__) . '/database/seed.sql', $sql);
echo "database/seed.sql written (" . count(tools_all()) . " tools)\n";
